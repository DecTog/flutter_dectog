// Builds llms.txt, the agent reference shipped inside the package,
// from the sources that are already kept true by tests:
//
//   doc/api-reference.md          every public type and member (also the docs
//                                 site's sdk/api-reference page)
//   README.md                     the init snippet and the routing rule
//   test/fixtures/url-cases.json  the link URLs the parser accepts and rejects
//
//   dart run tool/gen_llms.dart           write llms.txt
//   dart run tool/gen_llms.dart --check   exit 1 when llms.txt is out of date
//
// test/llms_test.dart runs the same check in `flutter test`.
import 'dart:convert';
import 'dart:io';

/// Reference sections in llms.txt order: types first, then the interface.
/// A section not listed here is appended at the end, never dropped.
const typeSections = ['DectogConfig', 'Install models'];
const linkSections = ['Link models'];
const interfaceSections = [
  'FlutterDectog',
  'Errors',
  'Widgets',
  'Package version',
];

class Reference {
  Reference(this.preamble, this.sections);
  final String preamble;
  final Map<String, String> sections;
}

/// Splits doc/api-reference.md into its preamble and its "## " sections,
/// ignoring headings inside fenced code.
Reference parseReference(String text) {
  final body = text.replaceFirst(RegExp(r'^<!--[\s\S]*?-->\s*'), '');
  final sections = <String, String>{};
  final preamble = StringBuffer();
  String? current;
  final buffer = StringBuffer();
  var fence = false;
  void close() {
    if (current != null) sections[current] = buffer.toString().trimRight();
    buffer.clear();
  }

  for (final line in body.split('\n')) {
    if (line.startsWith('```')) fence = !fence;
    if (!fence && line.startsWith('# ')) continue;
    if (!fence && line.startsWith('## ')) {
      close();
      current = line.substring(3).trim();
    }
    (current == null ? preamble : buffer).writeln(line);
  }
  close();
  return Reference(preamble.toString().trim(), sections);
}

/// The fenced dart blocks of [markdown], in order.
List<String> dartBlocks(String markdown) =>
    RegExp(
      r'```dart\n([\s\S]*?)```',
    ).allMatches(markdown).map((m) => m.group(1)!.trimRight()).toList();

String _section(Reference ref, String title) {
  final s = ref.sections[title];
  if (s == null) {
    throw StateError('doc/api-reference.md has no "## $title" section');
  }
  return s;
}

String _urlTable(String urlCasesJson) {
  final cases =
      (jsonDecode(urlCasesJson)['cases'] as List).cast<Map<String, dynamic>>();
  String config(Map<String, dynamic> c) => [
    'baseUrl `${c['baseUrl']}`',
    if (c['linkRootDomain'] != null) 'linkRootDomain `${c['linkRootDomain']}`',
  ].join(', ');
  String row(Map<String, dynamic> c) {
    final e = c['expect'] as Map<String, dynamic>?;
    final result =
        e == null
            ? 'not a link'
            : 'username `${e['username']}`, slug `${e['slug']}`';
    return '| `${c['url']}` | ${config(c)} | $result | ${c['name']} |';
  }

  final accepted = cases.where((c) => c['expect'] != null);
  final rejected = cases.where((c) => c['expect'] == null);
  return [
    '| URL | Config | Result | Case |',
    '|---|---|---|---|',
    ...accepted.map(row),
    ...rejected.map(row),
  ].join('\n');
}

String buildLlms({
  required String reference,
  required String readme,
  required String urlCasesJson,
  required String version,
}) {
  final ref = parseReference(reference);
  final inits =
      dartBlocks(
        readme,
      ).where((b) => b.contains('initialize(DectogConfig(')).toList();
  if (inits.length < 2) {
    throw StateError(
      'README.md needs the hosted and the self-hosted initialize() snippets',
    );
  }
  final handle = dartBlocks(readme).firstWhere(
    (b) => b.contains('onLinkClick.listen'),
    orElse: () => throw StateError('README.md has no onLinkClick snippet'),
  );
  final routing = RegExp(
    r'\*\*Routing vs credit\.\*\*[\s\S]*?```dart\n[\s\S]*?```',
  ).firstMatch(readme)?.group(0);
  if (routing == null) {
    throw StateError(
      'README.md has no "**Routing vs credit.**" paragraph and snippet',
    );
  }
  final listed = {...typeSections, ...linkSections, ...interfaceSections};
  final rest = ref.sections.keys.where((k) => !listed.contains(k));

  return [
    '# flutter_dectog $version',
    '',
    '> Flutter SDK for DecTog: links that open the app when it is installed and the store when it is not, deferred deep links, install attribution and post-install events. Hosted at https://app.dectog.com, or self-hosted.',
    '',
    'For AI agents working in an app that depends on flutter_dectog. Generated by tool/gen_llms.dart from doc/api-reference.md, README.md and test/fixtures/url-cases.json; do not edit by hand. Full documentation: https://docs.dectog.com/sdk/installation/ (every page in one file: https://docs.dectog.com/llms-full.txt).',
    '',
    ref.preamble,
    '',
    for (final t in typeSections) ...[_section(ref, t), ''],
    '## Routing an install',
    '',
    routing,
    '',
    for (final t in linkSections) ...[_section(ref, t), ''],
    '## Link URLs the SDK recognizes',
    '',
    'The cases test/url_parser_test.dart runs. `baseUrl` and `linkRootDomain` are the `DectogConfig` values; any other URL is not a DecTog link and is ignored.',
    '',
    _urlTable(urlCasesJson),
    '',
    '## Initialize and handle links',
    '',
    'Hosted (the SDK defaults to `https://app.dectog.com` and links on `{username}.dectog.com`):',
    '',
    '```dart',
    inits[0],
    '```',
    '',
    'Self-hosted:',
    '',
    '```dart',
    inits[1],
    '```',
    '',
    'Incoming links:',
    '',
    '```dart',
    handle,
    '```',
    '',
    for (final t in [...interfaceSections, ...rest]) ...[_section(ref, t), ''],
  ].join('\n');
}

String _pubspecVersion(String pubspec) =>
    RegExp(
      r'^version:\s*(\S+)',
      multiLine: true,
    ).firstMatch(pubspec)!.group(1)!;

/// llms.txt as it should be, from the files in [root].
String expectedLlms([String root = '.']) {
  String read(String path) => File('$root/$path').readAsStringSync();
  return buildLlms(
    reference: read('doc/api-reference.md'),
    readme: read('README.md'),
    urlCasesJson: read('test/fixtures/url-cases.json'),
    version: _pubspecVersion(read('pubspec.yaml')),
  );
}

void main(List<String> args) {
  final expected = expectedLlms();
  final file = File('llms.txt');
  final current = file.existsSync() ? file.readAsStringSync() : null;
  if (args.contains('--check')) {
    if (current != expected) {
      stderr.writeln(
        'llms.txt is out of date: run dart run tool/gen_llms.dart',
      );
      exitCode = 1;
    } else {
      stdout.writeln('llms.txt is up to date.');
    }
    return;
  }
  if (current == expected) {
    stdout.writeln('llms.txt is up to date.');
    return;
  }
  file.writeAsStringSync(expected);
  stdout.writeln('Wrote llms.txt');
}
